#!/usr/bin/env python3
"""
문체 금지 규칙 1차 필터 — 번역투·상투어·잠언체·코다체 (references/문체_금지규칙.md)
사용:  python3 style_check.py <파일.md> [--all]
  기본: `## 문항 N` 섹션 본문만 검사(verify.py와 동일 분할). --all: 파일 전체를 한 덩어리로 검사.
정규식은 1차 필터다. 히트 0건이어도 정의로 재독해야 하고, 히트가 문맥상 정당하면 사람이 판단한다.
"""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from verify import sections

RULES = {
    '번역투': [
        r'되어졌', r'에 의해', r'에 있어서?\b', r'함에 있어', r'에 대한 [가-힣]+을 (진행|수행)', r'을 가지게 되',
        r'관심을 가지', r'열정을 가지', r'책임감을 가지', r'를 통해 (성장|배웠|느꼈)', r'으?로부터', r'에게 있어',
        r'것으로 보여집니다', r'생각되어집니다', r'의 경우', r'적인 측면에서', r'하는 것을 (진행|수행)', r'수행을 완료',
        r'[가-힣]+(은|는|이|가) (저|나)에게 [가-힣 ]*(가르쳐|알려|깨닫게|보여) ?주',
    ],
    '상투어': [
        r'끊임없이', r'최선을 다', r'밤낮', r'누구보다', r'항상 고민', r'열정을', r'책임감을 갖', r'적극적으로 소통',
        r'밑거름', r'발판', r'한 걸음 더', r'값진 경험', r'소중한 경험', r'많은 것을 배', r'성장할 수 있었', r'한층 성장',
        r'시야를 넓', r'시너지', r'든든한', r'하나 된', r'원활한 소통', r'팀워크를 발휘', r'뼈를 묻', r'평생 헌신',
        r'최고의 전문가', r'발전에 이바지', r'미래를 선도', r'심도 있는', r'폭넓은', r'체계적인', r'성공적으로',
    ],
    '잠언체': [
        # 추상 개념이 주어인 진리 명제 (정상 서술 "이유는 ~입니다"는 잡지 않도록 주어를 한정)
        r'(신뢰|준비|의지|혁신|품질|책임|성장|본질|정답|원칙|열정|노력|성공|실패|기술|개발|운영|협업|소통|안정성|데이터|사람|일)(은|는|이란|란) [가-힣 ,·]+(입니다|이다|됩니다|된다|되고|나옵니다|나온다|나오고|갈립니다|갈린다)[\.,]',
        r'(은|는) 결국', r'에서 (나온다|나옵니다|나오고|나온다고|갈린다|갈립니다|시작된다|시작됩니다)',
        r'(라는|다는) (것을|점을|사실을|원칙을) (배웠|깨달았|확인했|알게 되었|알았)', r'(보다|아니라) [가-힣 ]+(가|이|를|을) (중요|먼저|우선)',
        r'만이 [가-힣 ]+수 있', r'없는 [가-힣]+(은|는) [가-힣 ]+(된다|됩니다|되고)', r'두 가지를 배웠습니다',
    ],
    '코다체': [
        r'(라고|이라고|다고) (믿습니다|확신합니다)\.', r'(가|이) 제 (기준|원칙|신념)입니다\.', r'되겠습니다\.\s*$', r'오래 하고 싶습니다',
        r'기여하겠습니다', r'보답하겠습니다', r'이바지하겠습니다', r'함께 성장하', r'역시 [가-힣 ]+(라고|이라고) (믿|생각)',
        r'(에서도|때도) [가-힣 ,·]+(지키겠습니다|반영하겠습니다|적용하겠습니다)\.\s*$', r'이렇게 저는',
        r'(으로|로) 답하겠습니다', r'(으로|로) 증명하겠습니다', r'(라고|이라고) 생각합니다\.\s*$',
    ],
}

def scan(text):
    hits = []
    for cat, pats in RULES.items():
        for p in pats:
            for m in re.finditer(p, text, flags=re.M):
                s, e = max(0, m.start() - 25), min(len(text), m.end() + 15)
                hits.append((cat, text[s:e].replace('\n', ' ')))
    return hits

def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__); sys.exit(1)
    path = args[0]
    if '--all' in args:
        blocks = [('전체', open(path, encoding='utf-8').read())]
    else:
        blocks = list(sections(path)) or [('전체', open(path, encoding='utf-8').read())]
    total = 0
    for n, sec in blocks:
        hits = scan(sec)
        total += len(hits)
        print(f"문항{n}: {'✅ 0건' if not hits else f'❌ {len(hits)}건'}")
        for cat, ctx in hits:
            print(f"  [{cat}] …{ctx}…")
    print(f"\n합계 {total}건 — 0건이어도 정의(문체_금지규칙.md)로 재독할 것")
    sys.exit(1 if total else 0)

if __name__ == '__main__':
    main()
